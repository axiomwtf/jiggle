use crate::error::JglcError;
use crate::manifest::{Manifest, CustomLanguage};
use crate::vfs::Vfs;
use std::path::Path;
use std::collections::HashMap;

/// Shell-quote a string for safe use in bash scripts
fn sh_quote(s: &str) -> String {
    // Use single quotes and escape any embedded single quotes
    format!("'{}'", s.replace("'", "'\\''"))

}

/// Generate build.sh for Unix systems
pub fn generate_build_sh(
    manifest: &Manifest,
    vfs: &Vfs,
    custom_languages: &[CustomLanguage],
    output_dir: &Path,
    target_win: bool,
) -> Result<(), JglcError> {
    let mut script = String::new();
    
    script.push_str("#!/bin/bash\n# Auto-generated by jglc - DO NOT EDIT\n\n");
    script.push_str("set -euo pipefail\n\n");
    
    // Use the directory of the script itself as the base
    script.push_str("SCRIPT_DIR=$(cd \"$(dirname \"${BASH_SOURCE[0]}\")\" && pwd)\n");
    script.push_str("cd \"$SCRIPT_DIR\"\n\n");
    
    // Extract the tar.xz bundle
    script.push_str("# Extract project bundle\n");
    script.push_str("if [ -f project.tar.xz ]; then\n");
    script.push_str("    mkdir -p jgl_build\n");
    script.push_str("    tar xf project.tar.xz -C jgl_build\n");
script.push_str("fi\n\n");
    script.push_str("# Initialize native objects list\n");
    script.push_str("NATIVE_OBJECTS=\"\"\n\n");
    
    // Generate dependency files restoration commands
    script.push_str("# Restore dependencies\n");
    
    for (lang, _entries) in &manifest.dependencies {
        let dep_file = crate::deps::get_dep_filename(lang, custom_languages)?;
        let restore_cmd = get_dependency_restore_cmd_unix(lang);
        
        if !restore_cmd.is_empty() {
            script.push_str(&format!("if [ -f jgl_build/{} ]; then\n", dep_file));
            script.push_str("    cd jgl_build\n");
            script.push_str(&format!("    {} 2>/dev/null || echo \"Warning: Failed to restore {} dependencies\"\n", restore_cmd, lang));
            script.push_str("    cd ..\n");
            script.push_str("fi\n\n");
        }
    }
    
    // Compile each language
    script.push_str("# Compile each language into object files for unified linking\n");
    script.push_str("cd jgl_build\n\n");
    
    // Group files by language, excluding dependency files
    let mut files_by_lang: HashMap<String, Vec<String>> = HashMap::new();
    for path in &vfs.ordered_files {
        if let Some(entry) = vfs.get(path) {
            if is_dep_file(path, custom_languages) {
                continue;
            }
            files_by_lang.entry(entry.language.clone()).or_default().push(path.clone());
        }
    }
    
    // Collect all .o files for final linking
    let mut object_files: Vec<String> = Vec::new();
    // Track which languages produce native objects (linkable into final binary)
    let mut native_objects: Vec<String> = Vec::new();
    
    // Rust compilation - compile combined crate directly to binary (rustc as linker for std)
    if let Some(files) = files_by_lang.get("rs") {
        if !files.is_empty() {
            script.push_str("# Rust\n");
            let has_cargo = vfs.contains("Cargo.toml");
            
            if has_cargo {
                script.push_str("# Rust with Cargo.toml - resolve deps, then compile combined crate to binary\n");
                script.push_str("if command -v cargo &> /dev/null; then\n");
                script.push_str("    echo \"Step 0: Creating dummy lib file for cargo...\"\n");
                script.push_str("    echo '' > jgl_dummy.rs\n");
                script.push_str("    echo \"Step 1: Building Rust dependencies with cargo...\"\n");
                script.push_str("    cargo build 2>&1 || echo \"Warning: cargo build had issues with deps\"\n");
                script.push_str("    # Step 2: Build extern flags from compiled dependency rlibs\n");
                script.push_str("    EXTERN_FLAGS=\"\"\n");
                script.push_str("    for rlib in $(find target/debug/deps -name '*.rlib' 2>/dev/null); do\n");
                script.push_str("        libname=$(basename \"$rlib\" | sed 's/^lib//' | sed 's/\\.rlib$//' | sed 's/-[a-f0-9]*$//')\n");
                script.push_str("        EXTERN_FLAGS=\"$EXTERN_FLAGS --extern $libname=$rlib\"\n");
                script.push_str("    done\n");
                script.push_str("    for rmeta in $(find target/debug/deps -name '*.rmeta' 2>/dev/null); do\n");
                script.push_str("        libname=$(basename \"$rmeta\" | sed 's/^lib//' | sed 's/\\.rmeta$//' | sed 's/-[a-f0-9]*$//')\n");
                script.push_str("        EXTERN_FLAGS=\"$EXTERN_FLAGS --extern $libname=$rmeta\"\n");
                script.push_str("    done\n");
                // Generate a combined main Rust file with module declarations
                // This avoids duplicate `main` symbol issues when linking multiple .o files
                script.push_str("    # Step 3: Generate combined main file (modules + main crate root)\n");
                script.push_str("    COMBINED_RS=\"jgl_combined_main.rs\"\n");
                // Start with lint suppressor (inner attributes must be at crate root start)
                script.push_str("    echo '#![allow(non_snake_case, non_camel_case_types, non_upper_case_globals)]' > \"$COMBINED_RS\"\n");
                // Add module declarations for secondary files (with semicolons!)
                let main_file = files.first();
                let mod_files: Vec<&String> = files.iter().skip(1).collect();
                if !mod_files.is_empty() {
                    script.push_str("    # Add module declarations for secondary Rust files\n");
                    for f in &mod_files {
                        let module_name = Path::new(f).file_stem().unwrap().to_string_lossy().to_string();
                        script.push_str(&format!("    echo 'mod {};' >> \"$COMBINED_RS\"\n", module_name));
                    }
                    script.push_str("    echo '' >> \"$COMBINED_RS\"\n");
                }
                // Append the main file's content (strip the lint suppressor line since it's now at top)
                if let Some(main_f) = main_file {
                    script.push_str(&format!("    cat {} | tail -n +2 >> \"$COMBINED_RS\" 2>/dev/null || echo \"Warning: Could not read {}\"\n", sh_quote(main_f), sh_quote(main_f)));
                }
                // Build link args for non-Rust objects (Go .a, C .o, embedded scripts)
                script.push_str("    # Step 4: Build link args for non-Rust objects\n");
                script.push_str("    LINK_ARGS=\"\"\n");
                script.push_str("    for go_a in *_0.a; do\n");
                script.push_str("        if [ -f \"$go_a\" ]; then LINK_ARGS=\"$LINK_ARGS -C link-arg=$go_a\"; fi\n");
                script.push_str("    done\n");
                script.push_str("    for embed in embed_*.o; do\n");
                script.push_str("        if [ -f \"$embed\" ]; then LINK_ARGS=\"$LINK_ARGS -C link-arg=$embed\"; fi\n");
                script.push_str("    done\n");
                script.push_str("    LINK_ARGS=\"$LINK_ARGS -C link-arg=-lm -C link-arg=-lpthread -C link-arg=-ldl\"\n");
                // Compile combined Rust source directly to final binary (rustc provides std runtime)
                script.push_str("    # Step 5: Compile + link everything into ONE unified binary\n");
                script.push_str("    echo \"Linking unified binary...\"\n");
                let bin_name = if target_win { "jgl_binary.exe" } else { "jgl_binary" };
                let target_flag = if target_win { " --target=x86_64-pc-windows-gnu" } else { "" };
                script.push_str(&format!("    rustc --edition 2024 -O -o {} --crate-type=bin{target_flag} \"$COMBINED_RS\" -L target/debug/deps/ $EXTERN_FLAGS $LINK_ARGS 2>&1 || echo \"Warning: Rust linking failed\"\n", bin_name, target_flag=target_flag));
                script.push_str(&format!("    if [ -f {} ]; then\n", bin_name));
                script.push_str(&format!("        echo \"Linked unified native binary: {} (Rust + Go + C + scripts)\"\n", bin_name));
                script.push_str("    fi\n");
                script.push_str("else\n");
                script.push_str("    echo \"Warning: cargo not found, trying rustc directly\"\n");
                // Without cargo - same combined approach but without extern flags
                script.push_str("    COMBINED_RS=\"jgl_combined_main.rs\"\n");
                script.push_str("    echo '#![allow(non_snake_case, non_camel_case_types, non_upper_case_globals)]' > \"$COMBINED_RS\"\n");
                let main_file = files.first();
                let mod_files: Vec<&String> = files.iter().skip(1).collect();
                if !mod_files.is_empty() {
                    for f in &mod_files {
                        let module_name = Path::new(f).file_stem().unwrap().to_string_lossy().to_string();
                        script.push_str(&format!("    echo 'mod {};' >> \"$COMBINED_RS\"\n", module_name));
                    }
                    script.push_str("    echo '' >> \"$COMBINED_RS\"\n");
                }
                if let Some(main_f) = main_file {
                    script.push_str(&format!("    cat {} | tail -n +2 >> \"$COMBINED_RS\"\n", sh_quote(main_f)));
                }
                script.push_str("    LINK_ARGS=\"\"\n");
                script.push_str("    for go_a in *_0.a; do\n");
                script.push_str("        if [ -f \"$go_a\" ]; then LINK_ARGS=\"$LINK_ARGS -C link-arg=$go_a\"; fi\n");
                script.push_str("    done\n");
                script.push_str("    for embed in embed_*.o; do\n");
                script.push_str("        if [ -f \"$embed\" ]; then LINK_ARGS=\"$LINK_ARGS -C link-arg=$embed\"; fi\n");
                script.push_str("    done\n");
                script.push_str("    LINK_ARGS=\"$LINK_ARGS -C link-arg=-lm -C link-arg=-lpthread -C link-arg=-ldl\"\n");
                let bin_name = if target_win { "jgl_binary.exe" } else { "jgl_binary" };
                let target_flag = if target_win { " --target=x86_64-pc-windows-gnu" } else { "" };
                script.push_str(&format!("    rustc --edition 2024 -O -o {} --crate-type=bin{target_flag} \"$COMBINED_RS\" $LINK_ARGS 2>&1 || echo \"Warning: Rust linking failed\"\n", bin_name, target_flag=target_flag));
                script.push_str(&format!("    if [ -f {} ]; then echo \"Linked unified native binary: {}\"; fi\n", bin_name, bin_name));
                script.push_str("fi\n\n");
            } else {
                script.push_str("# Rust (no Cargo.toml) - compiling combined crate to binary\n");
                script.push_str("if rustc --version &> /dev/null; then\n");
                script.push_str("    COMBINED_RS=\"jgl_combined_main.rs\"\n");
                script.push_str("    echo '#![allow(non_snake_case, non_camel_case_types, non_upper_case_globals)]' > \"$COMBINED_RS\"\n");
                let main_file = files.first();
                let mod_files: Vec<&String> = files.iter().skip(1).collect();
                if !mod_files.is_empty() {
                    for f in &mod_files {
                        let module_name = Path::new(f).file_stem().unwrap().to_string_lossy().to_string();
                        script.push_str(&format!("    echo 'mod {};' >> \"$COMBINED_RS\"\n", module_name));
                    }
                    script.push_str("    echo '' >> \"$COMBINED_RS\"\n");
                }
                if let Some(main_f) = main_file {
                    script.push_str(&format!("    cat {} | tail -n +2 >> \"$COMBINED_RS\"\n", sh_quote(main_f)));
                }
                script.push_str("    LINK_ARGS=\"\"\n");
                script.push_str("    for go_a in *_0.a; do\n");
                script.push_str("        if [ -f \"$go_a\" ]; then LINK_ARGS=\"$LINK_ARGS -C link-arg=$go_a\"; fi\n");
                script.push_str("    done\n");
                script.push_str("    for embed in embed_*.o; do\n");
                script.push_str("        if [ -f \"$embed\" ]; then LINK_ARGS=\"$LINK_ARGS -C link-arg=$embed\"; fi\n");
                script.push_str("    done\n");
                script.push_str("    LINK_ARGS=\"$LINK_ARGS -C link-arg=-lm -C link-arg=-lpthread -C link-arg=-ldl\"\n");
                let bin_name = if target_win { "jgl_binary.exe" } else { "jgl_binary" };
                let target_flag = if target_win { " --target=x86_64-pc-windows-gnu" } else { "" };
                script.push_str(&format!("    rustc --edition 2024 -O -o {} --crate-type=bin{target_flag} \"$COMBINED_RS\" $LINK_ARGS 2>&1 || echo \"Warning: Rust linking failed\"\n", bin_name, target_flag=target_flag));
                script.push_str(&format!("    if [ -f {} ]; then echo \"Linked unified native binary: {}\"; fi\n", bin_name, bin_name));
                script.push_str("else\n");
                script.push_str("    echo \"Warning: Rust compiler (rustc) not found, skipping Rust compilation\"\n");
                script.push_str("fi\n\n");
            }
        }
    }
    
    // Go compilation - compile to static archives for linking
    if let Some(files) = files_by_lang.get("go") {
        if !files.is_empty() {
            script.push_str("# Go - compiled as C archives for static linking\n");
            script.push_str("if command -v go &> /dev/null; then\n");
            for (i, f) in files.iter().enumerate() {
                let a_name = f.replace(".go", &format!("_{}.a", i));
                // Use the .a archive directly as linker input (contains Go runtime + cgo)
                script.push_str(&format!("    echo \"Compiling Go: {}\"\n", f));
                script.push_str(&format!("    go build -buildmode=c-archive -o {} {} 2>&1 || echo \"Warning: Go compilation failed for {}\"\n",
                    sh_quote(&a_name), sh_quote(f), sh_quote(f)));
                script.push_str(&format!("    if [ -f {} ]; then NATIVE_OBJECTS=\"$NATIVE_OBJECTS {}\"; fi\n", sh_quote(&a_name), sh_quote(&a_name)));
            }
            script.push_str("else\n");
            script.push_str("    echo \"Warning: Go compiler (go) not found, skipping Go compilation\"\n");
            script.push_str("fi\n\n");
        }
    }
    
    // C compilation
    if let Some(c_files) = files_by_lang.get("c") {
        if !c_files.is_empty() {
            script.push_str("# C\n");
            script.push_str("if command -v clang &> /dev/null; then\n");
            script.push_str("    CC=clang\n");
            script.push_str("elif command -v gcc &> /dev/null; then\n");
            script.push_str("    CC=gcc\n");
            script.push_str("else\n");
            script.push_str("    echo \"Warning: No C compiler found (clang or gcc), skipping C compilation\"\n");
            script.push_str("fi\n");
            for f in c_files {
                let out_name = f.replace(".c", ".o");
                object_files.push(out_name.clone());
                native_objects.push(out_name.clone());
                script.push_str(&format!("if [ -n \"${{CC:-}}\" ]; then $CC -O2 -c -o {} {} || echo \"Warning: Failed to compile {}\"; fi\n", sh_quote(&out_name), sh_quote(f), sh_quote(f)));
            }
            script.push_str("\n");
        }
    }
    
    // C++ compilation
    if let Some(cpp_files) = files_by_lang.get("cpp") {
        if !cpp_files.is_empty() {
            script.push_str("# C++\n");
            script.push_str("# Note: C++ functions must be wrapped in extern \"C\" for cross-language FFI\n");
            script.push_str("if command -v clang++ &> /dev/null; then\n");
            script.push_str("    CXX=clang++\n");
            script.push_str("elif command -v g++ &> /dev/null; then\n");
            script.push_str("    CXX=g++\n");
            script.push_str("else\n");
            script.push_str("    echo \"Warning: No C++ compiler found (clang++ or g++), skipping C++ compilation\"\n");
            script.push_str("fi\n");
            for f in cpp_files {
                let out_name = f.replace(".cpp", ".o");
                object_files.push(out_name.clone());
                native_objects.push(out_name.clone());
                script.push_str(&format!("if [ -n \"${{CXX:-}}\" ]; then $CXX -O2 -c -o {} {} || echo \"Warning: Failed to compile {}\"; fi\n", sh_quote(&out_name), sh_quote(f), sh_quote(f)));
            }
            script.push_str("\n");
        }
    }
    
    // Zig compilation
    if let Some(files) = files_by_lang.get("zig") {
        if !files.is_empty() {
            script.push_str("# Zig\n");
            script.push_str("if command -v zig &> /dev/null; then\n");
            for f in files {
                let out_name = f.replace(".zig", ".o");
                object_files.push(out_name.clone());
                native_objects.push(out_name.clone());
                script.push_str(&format!("    zig build-obj -O -o {} {} 2>&1 || echo \"Warning: Failed to compile {}\"\n", sh_quote(&out_name), sh_quote(f), sh_quote(f)));
            }
            script.push_str("else\n");
            script.push_str("    echo \"Warning: Zig compiler (zig) not found, skipping Zig compilation\"\n");
            script.push_str("fi\n\n");
        }
    }
    
    // Nim compilation
    if let Some(files) = files_by_lang.get("nim") {
        if !files.is_empty() {
            script.push_str("# Nim\n");
            script.push_str("if command -v nim &> /dev/null; then\n");
            for f in files {
                let base_name: String = f.chars().filter(|c| c.is_alphanumeric()).collect();
                let out_name = format!("_{}.o", base_name);
                object_files.push(out_name.clone());
                native_objects.push(out_name.clone());
                script.push_str(&format!("    nim c --noLinking --passC:-O2 -o:{} {} 2>&1 || echo \"Warning: Failed to compile {}\"\n", sh_quote(&out_name), sh_quote(f), sh_quote(f)));
            }
            script.push_str("else\n");
            script.push_str("    echo \"Warning: Nim compiler (nim) not found, skipping Nim compilation\"\n");
            script.push_str("fi\n\n");
        }
    }
    
    // Fortran compilation
    if let Some(files) = files_by_lang.get("f90") {
        if !files.is_empty() {
            script.push_str("# Fortran\n");
            script.push_str("if command -v gfortran &> /dev/null; then\n");
            for f in files {
                let out_name = f.replace(".f90", ".o");
                object_files.push(out_name.clone());
                native_objects.push(out_name.clone());
                script.push_str(&format!("    gfortran -O2 -c -o {} {} 2>&1 || echo \"Warning: Failed to compile {}\"\n", sh_quote(&out_name), sh_quote(f), sh_quote(f)));
            }
            script.push_str("else\n");
            script.push_str("    echo \"Warning: Fortran compiler (gfortran) not found, skipping Fortran compilation\"\n");
            script.push_str("fi\n\n");
        }
    }
    
    // JVM languages - compile to JAR, then embed as C data segment
    // The JAR is embedded as binary data in the unified binary
    // The JVM runtime is NOT bundled - declared as a runtime dependency
    if let Some(files) = files_by_lang.get("java") {
        if !files.is_empty() {
            script.push_str("# Java - compile to JAR, embed as C data segment\n");
            script.push_str("# JVM is NOT bundled - declared as a runtime dependency\n");
            script.push_str("if command -v javac &> /dev/null; then\n");
            script.push_str("    mkdir -p classes\n");
            script.push_str("    javac -d classes ");
            for f in files {
                script.push_str(&format!("{} ", sh_quote(f)));
            }
            script.push_str("2>&1 || echo \"Warning: Failed to compile Java\"\n");
            script.push_str("    jar cf jgl_java.jar -C classes . 2>/dev/null || true\n");
            script.push_str("else\n");
            script.push_str("    echo \"Warning: Java compiler (javac) not found, skipping Java compilation\"\n");
            script.push_str("fi\n\n");
        }
    }
    
    // Kotlin
    if let Some(files) = files_by_lang.get("kt") {
        if !files.is_empty() {
            script.push_str("# Kotlin - compile to JAR, embed as C data segment\n");
            script.push_str("# JVM is NOT bundled - declared as a runtime dependency\n");
            script.push_str("if command -v kotlinc &> /dev/null; then\n");
            script.push_str("    mkdir -p classes\n");
            script.push_str("    kotlinc -d classes ");
            for f in files {
                script.push_str(&format!("{} ", sh_quote(f)));
            }
            script.push_str("2>&1 || echo \"Warning: Failed to compile Kotlin\"\n");
            script.push_str("    jar cf jgl_kotlin.jar -C classes . 2>/dev/null || true\n");
            script.push_str("else\n");
            script.push_str("    echo \"Warning: Kotlin compiler (kotlinc) not found, skipping Kotlin compilation\"\n");
            script.push_str("fi\n\n");
        }
    }
    
    // Scala
    if let Some(files) = files_by_lang.get("scala") {
        if !files.is_empty() {
            script.push_str("# Scala - compile to JAR, embed as C data segment\n");
            script.push_str("# JVM is NOT bundled - declared as a runtime dependency\n");
            script.push_str("if command -v scalac &> /dev/null; then\n");
            script.push_str("    scalac ");
            for f in files {
                script.push_str(&format!("{} ", sh_quote(f)));
            }
            script.push_str("-d jgl_scala.jar 2>&1 || echo \"Warning: Failed to compile Scala\"\n");
            script.push_str("else\n");
            script.push_str("    echo \"Warning: Scala compiler (scalac) not found, skipping Scala compilation\"\n");
            script.push_str("fi\n\n");
        }
    }
    
    // C#
    if let Some(files) = files_by_lang.get("cs") {
        if !files.is_empty() {
            script.push_str("# C# - compile to DLL, embed as C data segment\n");
            script.push_str("# .NET runtime is NOT bundled - declared as a runtime dependency\n");
            script.push_str("if command -v csc &> /dev/null; then\n");
            script.push_str("    csc -target:library ");
            for f in files {
                script.push_str(&format!("{} ", sh_quote(f)));
            }
            script.push_str("-out:jgl_cs.dll 2>&1 || echo \"Warning: Failed to compile C#\"\n");
            script.push_str("else\n");
            script.push_str("    echo \"Warning: C# compiler (csc) not found, skipping C# compilation\"\n");
            script.push_str("fi\n\n");
        }
    }
    
    // Scripting languages and binary payloads - embed as C string data for unified binary
    // JS, TS, TSX, JSX, Python, Lua, BrightScript, and binary payloads (JARs, DLLs)
    // are all embedded as C data segments compiled to .o files and linked into the unified binary
    let script_langs = ["js", "ts", "tsx", "jsx", "py", "lua", "bs", "rb", "sh", "php"];
    let mut script_files: Vec<(&str, &String)> = Vec::new();
    for lang in &script_langs {
        if let Some(files) = files_by_lang.get(*lang) {
            for f in files {
                script_files.push((lang, f));
            }
        }
    }
    
    if !script_files.is_empty() {
        script.push_str("# Scripting languages - embedding source as C data segments\n");
        script.push_str("# These are compiled to .o files and linked into the unified binary\n");
        script.push_str("if command -v cc &> /dev/null || command -v gcc &> /dev/null; then\n");
        script.push_str("    if command -v cc &> /dev/null; then SCRIPT_CC=cc; else SCRIPT_CC=gcc; fi\n");
        script.push_str("    for script_file in *.js *.ts *.tsx *.jsx *.py *.lua *.bs *.rb *.sh *.php; do\n");
        script.push_str("        if [ -f \"$script_file\" ]; then\n");
        script.push_str("            # Convert filename to C variable name\n");
        script.push_str("            var_name=$(echo \"$script_file\" | tr '.' '_' | tr '-' '_')\n");
        script.push_str("            obj_name=\"embed_${var_name}.o\"\n");
        script.push_str("            echo \"Embedding $script_file as C data...\"\n");
        script.push_str("            # Create C wrapper with the file content as a string literal\n");
        script.push_str("            echo \"#include <stdint.h>\" > \"embed_${var_name}.c\"\n");
        script.push_str("            echo \"const char ${var_name}_name[] = \\\"$script_file\\\";\" >> \"embed_${var_name}.c\"\n");
        script.push_str("            printf \"const unsigned char ${var_name}_data[] = { \" >> \"embed_${var_name}.c\"\n");
        script.push_str("            od -An -v -t u1 \"$script_file\" | tr -d ' ' | tr '\\n' ',' | tr -d '\\n' | sed 's/,$//' >> \"embed_${var_name}.c\"\n");
        script.push_str("            echo \" };\" >> \"embed_${var_name}.c\"\n");
        script.push_str("            printf \"const uint32_t ${var_name}_len = %d;\" $(wc -c < \"$script_file\") >> \"embed_${var_name}.c\"\n");
        script.push_str("            $SCRIPT_CC -c -O2 -o \"$obj_name\" \"embed_${var_name}.c\" 2>/dev/null || echo \"Warning: Failed to embed $script_file\"\n");
        script.push_str("            if [ -f \"$obj_name\" ]; then\n");
        script.push_str("                NATIVE_OBJECTS=\"$NATIVE_OBJECTS $obj_name\"\n");
        script.push_str("            fi\n");
        script.push_str("        fi\n");
        script.push_str("    done\n");
        script.push_str("else\n");
        script.push_str("    echo \"Warning: No C compiler found for script embedding, skipping\"\n");
        script.push_str("fi\n\n");
    }
    
    // Embed binary payloads (JARs, DLLs) as C data segments
    // JVM and .NET are NOT bundled - declared as runtime dependencies
    // Only compiled artifacts are embedded as data
    script.push_str("# Embed binary payloads (JARs, DLLs) as C data segments\n");
    script.push_str("if command -v cc &> /dev/null || command -v gcc &> /dev/null; then\n");
    script.push_str("    if command -v cc &> /dev/null; then SCRIPT_CC=cc; else SCRIPT_CC=gcc; fi\n");
    script.push_str("    for jar_file in *.jar *.dll; do\n");
    script.push_str("        if [ -f \"$jar_file\" ]; then\n");
    script.push_str("            var_name=$(echo \"$jar_file\" | tr '.' '_' | tr '-' '_')\n");
    script.push_str("            obj_name=\"embed_${var_name}.o\"\n");
    script.push_str("            echo \"Embedding $jar_file as C data...\"\n");
    script.push_str("            echo \"#include <stdint.h>\" > \"embed_${var_name}.c\"\n");
    script.push_str("            echo \"const char ${var_name}_name[] = \\\"$jar_file\\\";\" >> \"embed_${var_name}.c\"\n");
    script.push_str("            printf \"const unsigned char ${var_name}_data[] = { \" >> \"embed_${var_name}.c\"\n");
    script.push_str("            od -An -v -t u1 \"$jar_file\" | tr -d ' ' | tr '\\n' ',' | tr -d '\\n' | sed 's/,$//' >> \"embed_${var_name}.c\"\n");
    script.push_str("            echo \" };\" >> \"embed_${var_name}.c\"\n");
    script.push_str("            printf \"const uint32_t ${var_name}_len = %d;\" $(wc -c < \"$jar_file\") >> \"embed_${var_name}.c\"\n");
    script.push_str("            $SCRIPT_CC -c -O2 -o \"$obj_name\" \"embed_${var_name}.c\" 2>/dev/null || echo \"Warning: Failed to embed $jar_file\"\n");
    script.push_str("            if [ -f \"$obj_name\" ]; then\n");
    script.push_str("                NATIVE_OBJECTS=\"$NATIVE_OBJECTS $obj_name\"\n");
    script.push_str("            fi\n");
    script.push_str("        fi\n");
    script.push_str("    done\n");
    script.push_str("fi\n\n");
    
    // Custom languages
    for custom in custom_languages {
        let files: Vec<&String> = files_by_lang.get(&custom.extension)
            .map(|v| v.iter().collect())
            .unwrap_or_default();
        if !files.is_empty() {
            script.push_str(&format!("# Custom language: {}\n", custom.extension));
            for f in &files {
                let out_name = f.replace(&format!(".{}", custom.extension), ".o");
                object_files.push(out_name.clone());
                native_objects.push(out_name.clone());
                let cmd = custom.compile_command
                    .replace("{in}", &sh_quote(f))
                    .replace("{out}", &sh_quote(&out_name))
                    .replace("{deps}", ".");
                script.push_str(&format!("{} 2>&1 || echo \"Warning: Failed to compile custom language {}\"\n", cmd, custom.extension));
            }
            script.push_str("\n");
        }
    }
    
    // Link native object files into final binary
    // Rust projects: binary already linked during Rust compilation (rustc as linker)
    // Non-Rust projects: use clang/gcc for final linking
    script.push_str("\n# Final link step\n");
    script.push_str("# Rust projects already linked jgl_binary during Rust compilation\n\n");
    
    let has_rust = files_by_lang.contains_key("rs");
    // Collect non-Rust native objects for fallback C/Go linking
    let non_rust_objects: Vec<&String> = native_objects.iter()
        .filter(|o| !o.contains("rust"))
        .collect();
    
    if !has_rust && !native_objects.is_empty() {
        // Pure C/Go/custom project - link with clang/gcc
        script.push_str("# Non-Rust project: link all native objects with clang/gcc\n");
        script.push_str("# Collect native object files\n");
        for obj in &native_objects {
            script.push_str(&format!("if [ -f {} ]; then NATIVE_OBJECTS=\"$NATIVE_OBJECTS {}\"; fi\n", sh_quote(obj), sh_quote(obj)));
        }
        script.push_str("# Also collect embedded script objects\n");
        script.push_str("for embed in embed_*.o; do\n");
        script.push_str("    if [ -f \"$embed\" ]; then NATIVE_OBJECTS=\"$NATIVE_OBJECTS $embed\"; fi\n");
        script.push_str("done\n");
        script.push_str("# Collect Go .a archives\n");
        script.push_str("for go_a in *_0.a; do\n");
        script.push_str("    if [ -f \"$go_a\" ]; then NATIVE_OBJECTS=\"$NATIVE_OBJECTS $go_a\"; fi\n");
        script.push_str("done\n");
        script.push_str("# Collect custom language objects\n");
        script.push_str("for calc_o in *.o; do\n");
        script.push_str("    case \"$calc_o\" in embed_*|rust*) continue ;; esac\n");
        script.push_str("    if [ -f \"$calc_o\" ]; then NATIVE_OBJECTS=\"$NATIVE_OBJECTS $calc_o\"; fi\n");
        script.push_str("done\n");
        script.push_str("\nif [ -n \"$NATIVE_OBJECTS\" ]; then\n");
        script.push_str("    if command -v clang &> /dev/null; then\n");
        script.push_str("        LINKER=clang\n");
        script.push_str("    elif command -v gcc &> /dev/null; then\n");
        script.push_str("        LINKER=gcc\n");
        script.push_str("    else\n");
        script.push_str("        echo \"Warning: No linker found (clang/gcc), skipping final link\"\n");
        script.push_str("        LINKER=\"\"\n");
        script.push_str("    fi\n");
        script.push_str("    \n");
        let bin_name = if target_win { "jgl_binary.exe" } else { "jgl_binary" };
        script.push_str("    if [ -n \"${LINKER:-}\" ]; then\n");
        script.push_str(&format!("        $LINKER -o {} $NATIVE_OBJECTS -lm -lpthread -ldl\n", bin_name));
        script.push_str(&format!("        echo \"Linked unified native binary: {}\"\n", bin_name));
        script.push_str("        echo \"Note: C++ functions must be wrapped in extern \\\"C\\\" for cross-language FFI\"\n");
        script.push_str("        echo \"      Go c-archive objects require Go runtime initialization\"\n");
        script.push_str("    fi\n");
        script.push_str("fi\n");
    } else if has_rust {
        // Rust project - binary already linked by rustc
        let bin_name = if target_win { "jgl_binary.exe" } else { "jgl_binary" };
        script.push_str("# Rust project - unified binary linked during Rust compilation\n");
        script.push_str(&format!("if [ -f {} ]; then\n", bin_name));
        script.push_str(&format!("    echo \"Unified native binary: {} (linked with Rust std runtime)\"\n", bin_name));
        script.push_str("else\n");
        script.push_str(&format!("    echo \"Warning: {} not found - Rust linking may have failed\"\n", bin_name));
        script.push_str("fi\n");
    } else {
        script.push_str("# No native object files to link\n");
        script.push_str("echo \"No native object files found - nothing to link\"\n");
    }
    
    // Report runtime dependencies (JVM, .NET) - NOT bundled
    script.push_str("\n# Runtime dependencies (NOT bundled - declared as runtime deps)\n");
    script.push_str("if [ -f jgl_java.jar ]; then\n");
    script.push_str("    echo \"Java JAR: jgl_java.jar (requires JVM at runtime)\"\n");
    script.push_str("fi\n");
    script.push_str("if [ -f jgl_kotlin.jar ]; then\n");
    script.push_str("    echo \"Kotlin JAR: jgl_kotlin.jar (requires JVM at runtime)\"\n");
    script.push_str("fi\n");
    script.push_str("if [ -f jgl_scala.jar ]; then\n");
    script.push_str("    echo \"Scala JAR: jgl_scala.jar (requires JVM at runtime)\"\n");
    script.push_str("fi\n");
    script.push_str("if [ -f jgl_cs.dll ]; then\n");
    script.push_str("    echo \"C# DLL: jgl_cs.dll (requires .NET runtime)\"\n");
    script.push_str("fi\n");
    
    script.push_str("\ncd ..\n");
    script.push_str("echo \"Compilation complete. See jgl_build/ for outputs.\"\n");
    
    let build_sh_path = output_dir.join("build.sh");
    std::fs::write(&build_sh_path, script).map_err(|e| JglcError::Io(e))?;
    
    // Make executable
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut perms = std::fs::metadata(&build_sh_path).map_err(|e| JglcError::Io(e))?.permissions();
        perms.set_mode(0o755);
        std::fs::set_permissions(&build_sh_path, perms).map_err(|e| JglcError::Io(e))?;
    }
    
    Ok(())
}

/// Check if a path is a dependency file
fn is_dep_file(path: &str, custom_languages: &[CustomLanguage]) -> bool {
    let dep_files = ["Cargo.toml", "package.json", "go.mod", "requirements.txt", 
                         "pom.xml", "packages.config", "Gemfile", "composer.json", 
                         "build.zig.zon", "jgl.nimble", 
                         "jgl-scm-1.rockspec", 
                         "vcpkg.json", "fpm.toml"];
    
    if dep_files.contains(&path) {
        return true;
    }
    
    custom_languages.iter().any(|cl| path == cl.dep_file)
}

/// Get the dependency restoration command for Unix systems
fn get_dependency_restore_cmd_unix(lang: &str) -> &'static str {
    match lang {
        "rs" => "cargo fetch",
        "js" | "ts" | "tsx" | "jsx" => "npm install --omit=dev",
        "go" => "go mod download",
        "py" => "pip install -r requirements.txt",
        "rb" => "bundle install",
        "php" => "composer install",
        "lua" => "luarocks install",
        "f90" => "fpm install",
        "c" | "cpp" => "vcpkg install",
        _ => "",
    }
}

